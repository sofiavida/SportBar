const LANG_NAMES = { es: "Español", en: "English", fr: "Français", pt: "Português" };
const LANG_FLAGS = { es: "🇲🇽", en: "🇬🇧", fr: "🇫🇷", pt: "🇵🇹" };

function getCurrentLang() { return localStorage.getItem("ceiba25_lang") || "es"; }
function setCurrentLang(lang) { localStorage.setItem("ceiba25_lang", lang); }

function applyTranslations(lang) {
  const dict = translations[lang] || translations.es;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  const waBtn = document.querySelector(".wa-float");
  if (waBtn) {
    waBtn.setAttribute("aria-label", dict.common_waAria);
    const phone = "529841188727";
    const msg = encodeURIComponent(dict.common_waMessage);
    waBtn.setAttribute("href", `https://wa.me/${phone}?text=${msg}`);
  }
  document.querySelectorAll(".lang-pill").forEach(btn => {
    btn.classList.toggle("lang-pill--active", btn.dataset.lang === lang);
  });
  document.documentElement.setAttribute("lang", lang);
}

function buildLangSelector(container) {
  const langs = ["es", "en", "fr", "pt"];
  container.innerHTML = "";
  langs.forEach(lang => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "lang-pill";
    btn.dataset.lang = lang;
    btn.setAttribute("aria-label", LANG_NAMES[lang]);
    btn.innerHTML = `<span class="lang-pill__flag">${LANG_FLAGS[lang]}</span><span class="lang-pill__code">${lang.toUpperCase()}</span>`;
    btn.addEventListener("click", () => {
      setCurrentLang(lang);
      applyTranslations(lang);
    });
    container.appendChild(btn);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  const container = document.querySelector(".lang-selector");
  if (container) buildLangSelector(container);
  applyTranslations(getCurrentLang());
});
